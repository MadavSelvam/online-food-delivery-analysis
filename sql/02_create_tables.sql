USE online_food_delivery;

DROP TABLE IF EXISTS food_delivery_orders;

CREATE TABLE food_delivery_orders (
    Order_ID VARCHAR(50),
    Customer_ID VARCHAR(50),
    Customer_Age INT,
    Customer_Gender VARCHAR(20),
    City VARCHAR(50),
    Area VARCHAR(50),
    Restaurant_ID VARCHAR(50),
    Restaurant_Name VARCHAR(255),
    Cuisine_Type VARCHAR(50),
    Order_Date DATE,
    Order_Time VARCHAR(20),
    Delivery_Time_Min DECIMAL(10,2),
    Distance_km DECIMAL(10,2),
    Order_Value DECIMAL(12,2),
    Discount_Applied DECIMAL(12,2),
    Final_Amount DECIMAL(12,2),
    Payment_Mode VARCHAR(50),
    Order_Status VARCHAR(30),
    Cancellation_Reason VARCHAR(100),
    Delivery_Partner_ID VARCHAR(50),
    Delivery_Rating DECIMAL(3,2),
    Restaurant_Rating DECIMAL(3,2),
    Order_Day VARCHAR(20),
    Peak_Hour VARCHAR(20),
    Profit_Margin DECIMAL(5,4),

    Order_Year INT,
    Order_Month_Num INT,
    Order_Month VARCHAR(20),
    Order_Quarter VARCHAR(10),
    Day_Name VARCHAR(20),
    Is_Weekend VARCHAR(10),
    Age_Group VARCHAR(20),
    Distance_Category VARCHAR(50),
    Delivery_Speed_Category VARCHAR(50),
    Discount_Category VARCHAR(30),
    Discount_Percentage DECIMAL(10,2),
    Order_Value_Category VARCHAR(50),
    Is_Delivered INT,
    Is_Cancelled INT,
    Customer_Order_Count INT,
    Customer_Type VARCHAR(30),
    Delivery_Rating_Category VARCHAR(30),
    Restaurant_Rating_Category VARCHAR(30)
);